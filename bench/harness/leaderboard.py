#!/usr/bin/env python3
"""Regenerate research/results/LEADERBOARD.md from the result JSON files.

Usage: python3 bench/harness/leaderboard.py [--results DIR] [--out FILE]

The leaderboard lists every committed run (newest first) with its verdict and
the candidate's speedup over Blake `main` and over stock Lake, and a per-machine
"best so far" table of Blake's cumulative speedup over Lake. Only *standard*
runs (default sweep, enforced caps, clean tree) whose candidate was correct and
whose commit is reachable from `main` count for "best", so progress toward the
target is visible without comparing absolute times across machines. The
maintainer regenerates this file after merging; contributors do not commit it.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RESULTS = ROOT / "research" / "results"
PRIMARY = ("noop", "leaf", "swarm", "hub")


def fmt(x: float | None) -> str:
    return f"{x:.3f}x" if isinstance(x, (int, float)) else "-"


def load(results_dir: Path) -> list[dict]:
    runs = []
    for p in sorted(results_dir.glob("*.json")):
        try:
            r = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if r.get("schema") not in (1, 2):
            continue
        r["_file"] = p.name
        runs.append(r)
    runs.sort(key=lambda r: r["timestamp"], reverse=True)
    return runs


def speed(r: dict, tool: str, base: str) -> dict:
    return r.get("speedup", {}).get(tool, {}).get(f"vs_{base}", {})


def correct(r: dict, tool: str) -> str:
    c = r.get("correctness", {}).get(tool)
    if not c:
        return "n/a"
    ok = all(v.get("identical") and v.get("builds_ok", True) and v.get("break_ok", True) for v in c.values())
    return "yes" if ok else "**NO**"


def on_main(commit: str) -> bool:
    for ref in ("origin/main", "main"):
        p = subprocess.run(["git", "merge-base", "--is-ancestor", commit, ref], cwd=ROOT, capture_output=True)
        if p.returncode == 0:
            return True
    return False


def render(runs: list[dict]) -> str:
    out = ["# Leaderboard", "",
           "Generated by `bench/harness/leaderboard.py` after merges; do not edit by hand.",
           "Speedups are geometric means over the corpora of a run (median wall-clock of",
           "the baseline divided by the candidate's). `primary` covers noop, leaf, swarm,",
           "and hub. Runs on different machines are only comparable through these ratios.",
           ""]
    out += ["## Best Blake vs stock Lake, per machine (standard runs, merged commits only)", "",
            "| machine | cpus | commit | label | date | primary | noop | leaf | swarm | hub | cold |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    best: dict[str, dict] = {}
    for r in runs:
        s = speed(r, "candidate", "lake")
        if "primary_geomean" not in s or correct(r, "candidate") != "yes":
            continue
        if not r.get("standard", False) or not on_main(r["git"]["commit"]):
            continue
        mid = r["machine"]["id"]
        if mid not in best or s["primary_geomean"] > speed(best[mid], "candidate", "lake")["primary_geomean"]:
            best[mid] = r
    for mid, r in sorted(best.items()):
        s = speed(r, "candidate", "lake")
        out.append(f"| {mid} | {r['machine']['caps']['cpu_count']} | {r['git']['commit'][:7]} | {r.get('label', '')} | "
                   f"{r['timestamp'][:10]} | **{fmt(s.get('primary_geomean'))}** | "
                   + " | ".join(fmt(s.get(k)) for k in (*PRIMARY, "cold")) + " |")
    if not best:
        out.append("| (no qualifying runs yet) | | | | | | | | | | |")
    out += ["", "## All committed runs (newest first)", "",
            "| date (UTC) | machine | cpus | branch | commit | label | verdict | vs main primary | vs lake primary | correct | standard | duration | file |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        sm = speed(r, "candidate", "main")
        sl = speed(r, "candidate", "lake")
        dirty = "+" if r["git"].get("dirty") else ""
        verdict = r.get("verdict", {}).get("overall", "-")
        out.append(f"| {r['timestamp'][:16].replace('T', ' ')} | {r['machine']['id']} | {r['machine']['caps']['cpu_count']} | "
                   f"{r['git']['branch']} | {r['git']['commit'][:7]}{dirty} | {r.get('label', '')} | {verdict} | "
                   f"{fmt(sm.get('primary_geomean'))} | {fmt(sl.get('primary_geomean'))} | {correct(r, 'candidate')} | "
                   f"{'yes' if r.get('standard') else 'no'} | {int(r.get('duration_s', 0)) // 60} min | `{r['_file']}` |")
    out += ["", "## Per-scenario detail of the newest standard run per machine", ""]
    seen = set()
    for r in runs:
        mid = r["machine"]["id"]
        if mid in seen or not r.get("standard"):
            continue
        seen.add(mid)
        caps = r["machine"]["caps"]
        out.append(f"### {mid}: {r['machine']['cpu']} ({caps['cpu_count']} cpus, {caps['mem_gb']} GB cap), "
                   f"{r['timestamp'][:10]}, commit {r['git']['commit'][:7]}")
        out.append("")
        tools = r["tool_order"]
        out.append("| corpus | scenario | " + " | ".join(tools) + " |")
        out.append("|---|---|" + "---|" * len(tools))
        for cfg, per_tool in r["measurements"].items():
            for scen in ("cold", *PRIMARY):
                cells = []
                for t in tools:
                    m = per_tool.get(t, {}).get(scen, {}).get("median_wall_s")
                    cells.append(f"{m:.2f} s" if m is not None else "-")
                out.append(f"| {cfg} | {scen} | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default=str(RESULTS))
    ap.add_argument("--out", default=str(RESULTS / "LEADERBOARD.md"))
    args = ap.parse_args()
    runs = load(Path(args.results))
    Path(args.out).write_text(render(runs), encoding="utf-8")
    print(f"wrote {args.out} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
